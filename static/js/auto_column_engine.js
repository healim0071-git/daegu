    sanitized = sanitized.replace(/부작용 없는|부작용없는/g, '부담을 낮춘');
    sanitized = sanitized.replace(/100% 치료|100% 완치/g, '체계적인 치료');
    sanitized = sanitized.replace(/근본적 해결/g, '단계적 원인 조절');
    sanitized = sanitized.replace(/유일한 치료/g, '유익한 치료 대안');
